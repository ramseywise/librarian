"""Validate the drills and interview rounds against the curriculum and generate a crosswalk.

    librarian courses check crosswalk           # validate, then write the crosswalk
    librarian courses check crosswalk --check   # validate, exit 1 if the written crosswalk is stale

Reads only public files (`git ls-files -co --exclude-standard` under `programming/drills/` and
`interviewing/`), never `data/courses/private/`. A link that reaches the private tree is skipped
without being named: `librarian wiki check` owns that blocker.

Checks, one line per problem, exit 1 on any:
- every `units:` entry in drill and round frontmatter exists, relative to the courses dir;
- every relative link in those files resolves and does not point at a gitignored file.
programming/drills/coding/dsa/ is upstream material, so its links are not checked and it has no units.

`units:` accepts an inline list or a YAML block list, of folders or single lessons:
    units: [programming/sql, data-analytics/06-applied-analyses/06-sql-for-analytics.md]

Output goes to `.cache/crosswalk.md` (gitignored), or `--out`. Unlike the sibling it does not write
into the courses tree, where every file is a lesson or lesson metadata.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from collections.abc import Sequence
from pathlib import Path
from urllib.parse import unquote

from librarian.config import get_settings
from librarian.courses.checks.common import (
    FENCE,
    default_root,
    git_ignored,
    public_files,
    split_front,
)
from librarian.wiki.course_leaks import reaches_private

ROOTS = ("programming/drills/", "interviewing/")
DRILLS = "programming/drills/"
SKIP_LINKS = "programming/drills/coding/dsa/"
LINK = re.compile(r"!?\[[^\]\n]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
HEADER = """# Crosswalk: curriculum to practice

Generated by `librarian courses check crosswalk` from `units:` frontmatter. A unit missing here has no
drill or round that names it yet, which does not always mean it is untested: fields are left out where
the mapping is unclear.
"""


def default_out() -> Path:
    return get_settings().cache_dir / "crosswalk.md"


def units_of(text: str) -> list[str]:
    front, _ = split_front(text)
    lines = front.splitlines()
    for i, line in enumerate(lines):
        if not line.startswith("units:"):
            continue
        rest = line[len("units:") :].strip()
        if rest:
            return [u.strip().strip("'\"") for u in rest.strip("[]").split(",") if u.strip()]
        found = []
        for item in lines[i + 1 :]:
            if not item.startswith((" ", "-")) or not item.strip().startswith("-"):
                break
            found.append(item.strip()[1:].strip().strip("'\""))
        return found
    return []


def link_targets(text: str) -> list[str]:
    out = []
    for target in LINK.findall(FENCE.sub("", text)):
        if re.match(r"[a-zA-Z][a-zA-Z+.-]*:|#|//", target):
            continue
        path = unquote(target.split("#", 1)[0])
        if path:
            out.append(path)
    return out


def validate(files: dict[str, str], root: Path) -> tuple[list[str], dict[str, list[str]]]:
    """(problem lines, units per file) for `files` (root-relative name -> text)."""
    problems: list[str] = []
    units: dict[str, list[str]] = {}
    pending: list[tuple[str, str]] = []
    for name, text in files.items():
        found = units_of(text)
        if found:
            units[name] = found
        for unit in found:
            unit = unit.rstrip("/")
            if not (root / unit).exists():
                problems.append(f"{name}: unit does not exist: {unit}")
            else:
                pending.append((name, unit))
        if name.startswith(SKIP_LINKS):
            continue
        base = (root / name).parent
        for target in link_targets(text):
            if reaches_private(target, root / name, root):
                continue
            abs_path = (base / unquote(target)).resolve()
            try:
                to = abs_path.relative_to(root.resolve()).as_posix()
            except ValueError:
                problems.append(f"{name}: link leaves the courses dir: {target}")
                continue
            if not abs_path.exists():
                problems.append(f"{name}: broken link: {target}")
            else:
                pending.append((name, to))
    bad = git_ignored(root, sorted({to for _, to in pending}))
    for name, to in pending:
        if to in bad:
            problems.append(f"{name}: points at an ignored path: {to}")
    return sorted(set(problems)), units


def label(name: str) -> str:
    parts = name.split("/")
    if name.startswith("interviewing/rounds/") and len(parts) > 3:
        return parts[2] if parts[-1] == "README.md" else f"{parts[2]}/{Path(parts[-1]).stem}"
    return Path(name).stem


def generate(units: dict[str, list[str]]) -> str:
    """The crosswalk markdown. Unit and lesson names are plain text: the file sits outside the tree."""
    table: dict[str, dict[str, set[str]]] = defaultdict(lambda: {"rounds": set(), "drills": set()})
    for name, found in units.items():
        kind = "drills" if name.startswith(DRILLS) else "rounds"
        for unit in found:
            table[unit.rstrip("/")][kind].add(name)
    lines = [HEADER]
    subjects: dict[str, list[str]] = defaultdict(list)
    for unit in table:
        subjects[unit.split("/")[0]].append(unit)
    for subject in sorted(subjects):
        lines += [f"## {subject}", "", "| Unit | Rounds | Drills |", "|---|---|---|"]
        for unit in sorted(subjects[subject]):
            cells = [
                ", ".join(f"`{n.removesuffix('.md')}`" for n in sorted(table[unit][k])) or "-"
                for k in ("rounds", "drills")
            ]
            lines.append(f"| `{unit}` | {cells[0]} | {cells[1]} |")
        lines.append("")
    return "\n".join(lines)


def run(root: Path, out: Path, check: bool = False) -> tuple[int, list[str]]:
    """Validate and write (or compare) the crosswalk. (exit code, output lines)."""
    names = [n for n in public_files(root, *ROOTS) if n.endswith(".md")]
    files = {n: (root / n).read_text(encoding="utf-8") for n in names if (root / n).is_file()}
    problems, units = validate(files, root)
    lines = list(problems)
    lines.append(
        f"crosswalk: {len(files)} markdown files, {len(units)} with units, "
        f"{len({u for us in units.values() for u in us})} distinct units, {len(problems)} problems"
    )
    if problems:
        return 1, lines
    text = generate(units)
    if check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            lines.append(f"crosswalk: {out.name} is stale; run `make crosswalk`")
            return 1, lines
        return 0, lines
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    lines.append(f"crosswalk: wrote {out}")
    return 0, lines


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="librarian courses check crosswalk", description=(__doc__ or "").split("\n")[0]
    )
    ap.add_argument("--root", type=Path, default=None, help="courses dir (default: data/courses)")
    ap.add_argument(
        "--out", type=Path, default=None, help="crosswalk file (default: .cache/crosswalk.md)"
    )
    ap.add_argument(
        "--check", action="store_true", help="do not write; exit 1 if the crosswalk is stale"
    )
    args = ap.parse_args(argv)
    root = (args.root or default_root()).resolve()
    code, lines = run(root, args.out or default_out(), args.check)
    print("\n".join(lines))
    return code


if __name__ == "__main__":
    sys.exit(main())
